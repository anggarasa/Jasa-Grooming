import crypto from "crypto";
import { env } from "@/config/env";

const ALGORITHM = "aes-256-gcm";
const IV_LENGTH = 12; // 96-bit recommended for GCM
const AUTH_TAG_LENGTH = 16; // 128-bit authentication tag

/**
 * Derives a consistent 32-byte key buffer from a secret string using SHA-256
 */
function deriveKey(secret?: string): Buffer {
  const keySource = secret || env.GOOGLE_TOKEN_ENCRYPTION_KEY || "pawcare-google-token-encryption-key-min-32-chars!";
  return crypto.createHash("sha256").update(keySource, "utf8").digest();
}

/**
 * Encrypts a plaintext string using AES-256-GCM.
 * Returns a colon-delimited string formatted as: `ivHex:authTagHex:encryptedHex`
 */
export function encrypt(plaintext: string, secretKey?: string): string {
  if (!plaintext) {
    return "";
  }

  const key = deriveKey(secretKey);
  const iv = crypto.randomBytes(IV_LENGTH);
  const cipher = crypto.createCipheriv(ALGORITHM, key, iv, {
    authTagLength: AUTH_TAG_LENGTH,
  });

  const encryptedBuffer = Buffer.concat([
    cipher.update(plaintext, "utf8"),
    cipher.final(),
  ]);

  const authTag = cipher.getAuthTag();

  return `${iv.toString("hex")}:${authTag.toString("hex")}:${encryptedBuffer.toString("hex")}`;
}

/**
 * Decrypts an encrypted ciphertext generated by `encrypt()`.
 * Throws an Error if the ciphertext format is invalid or authentication tag check fails.
 */
export function decrypt(ciphertext: string, secretKey?: string): string {
  if (!ciphertext) {
    return "";
  }

  const parts = ciphertext.split(":");
  if (parts.length !== 3) {
    throw new Error("Format data terenkripsi tidak valid.");
  }

  const [ivHex, authTagHex, encryptedHex] = parts;
  const iv = Buffer.from(ivHex, "hex");
  const authTag = Buffer.from(authTagHex, "hex");
  const encryptedBuffer = Buffer.from(encryptedHex, "hex");

  if (iv.length !== IV_LENGTH || authTag.length !== AUTH_TAG_LENGTH) {
    throw new Error("Metadata enkripsi (IV atau auth tag) tidak valid.");
  }

  const key = deriveKey(secretKey);
  const decipher = crypto.createDecipheriv(ALGORITHM, key, iv, {
    authTagLength: AUTH_TAG_LENGTH,
  });

  decipher.setAuthTag(authTag);

  try {
    const decryptedBuffer = Buffer.concat([
      decipher.update(encryptedBuffer),
      decipher.final(),
    ]);

    return decryptedBuffer.toString("utf8");
  } catch {
    throw new Error("Gagal mendekripsi data: verifikasi integritas data (auth tag) gagal.");
  }
}

export interface OAuthStatePayload {
  businessId: string;
  userId: string;
  nonce: string;
  timestamp: number;
}

/**
 * Generates an HMAC-SHA256 signed OAuth state string to prevent CSRF and replay attacks.
 */
export function generateOAuthState(data: { businessId: string; userId: string }): string {
  const secret = env.GOOGLE_OAUTH_STATE_SECRET || "google-oauth-state-secret-min-32-chars-long-tampilkit";
  const nonce = crypto.randomBytes(16).toString("hex");
  const timestamp = Date.now();

  const payload: OAuthStatePayload = {
    businessId: data.businessId,
    userId: data.userId,
    nonce,
    timestamp,
  };

  const payloadStr = JSON.stringify(payload);
  const payloadBase64 = Buffer.from(payloadStr, "utf8").toString("base64url");
  const signature = crypto
    .createHmac("sha256", secret)
    .update(payloadBase64)
    .digest("base64url");

  return `${payloadBase64}.${signature}`;
}

/**
 * Verifies and parses an HMAC-SHA256 signed OAuth state string.
 * Throws an Error if expired, altered, or malformed.
 */
export function verifyOAuthState(
  stateString: string,
  maxAgeMs = 15 * 60 * 1000 // 15 minutes validity
): OAuthStatePayload {
  if (!stateString || typeof stateString !== "string") {
    throw new Error("OAuth state tidak valid atau kosong.");
  }

  const parts = stateString.split(".");
  if (parts.length !== 2) {
    throw new Error("Format OAuth state tidak valid.");
  }

  const [payloadBase64, signature] = parts;
  const secret = env.GOOGLE_OAUTH_STATE_SECRET || "google-oauth-state-secret-min-32-chars-long-tampilkit";

  const expectedSignature = crypto
    .createHmac("sha256", secret)
    .update(payloadBase64)
    .digest("base64url");

  const expectedBuffer = Buffer.from(expectedSignature, "utf8");
  const actualBuffer = Buffer.from(signature, "utf8");

  if (
    expectedBuffer.length !== actualBuffer.length ||
    !crypto.timingSafeEqual(expectedBuffer, actualBuffer)
  ) {
    throw new Error("Tanda tangan OAuth state tidak valid (kemungkinan pemalsuan permintaan).");
  }

  let payload: OAuthStatePayload;
  try {
    const jsonStr = Buffer.from(payloadBase64, "base64url").toString("utf8");
    payload = JSON.parse(jsonStr);
  } catch {
    throw new Error("OAuth state payload rusak atau gagal didekode.");
  }

  if (!payload.businessId || !payload.userId || !payload.timestamp || !payload.nonce) {
    throw new Error("Properti OAuth state tidak lengkap.");
  }

  const age = Date.now() - payload.timestamp;
  if (age < 0 || age > maxAgeMs) {
    throw new Error("OAuth state telah kedaluwarsa. Silakan mulai ulang proses integrasi.");
  }

  return payload;
}

/**
 * Computes a SHA-256 hash of a webhook verification token for safe database indexing
 */
export function hashWebhookToken(token: string): string {
  return crypto.createHash("sha256").update(token, "utf8").digest("hex");
}
